function updateProgramOptions(){
  const tour = tourSelect.value;
  const options = tourPrograms[tour] || [];
  programPreference.innerHTML = options.length
    ? '<option value="">Select a program / season</option>' + options.map(x => `<option>${x}</option>`).join("")
    : '<option value="">Select a tour first</option>';
  programPreference.disabled = !tour;
}
if(tourSelect && programPreference){
  tourSelect.addEventListener("change", updateProgramOptions);
  updateProgramOptions();
}

document.querySelectorAll("[data-service]").forEach(btn=>{
  btn.addEventListener("click",()=>{
    const service = btn.dataset.service;
    if(requestType) requestType.value = service;
    if(service === "Flight Ticket Reservation" || service === "Cruise Journey") {
      if(tourSelect) tourSelect.value = "Other / Tailor-made Trip";
      updateProgramOptions();
    }
    updateServiceFields();
    setTimeout(()=>document.getElementById("contact")?.scrollIntoView({behavior:"smooth",block:"start"}),40);
  });
});

function updateServiceFields(){
  const isFlight = requestType && requestType.value === "Flight Ticket Reservation";
  const isCruise = requestType && requestType.value === "Cruise Journey";
  if(flightFields) flightFields.hidden = !isFlight;
  if(cruiseFields) cruiseFields.hidden = !isCruise;
  if(generalTripFields) generalTripFields.hidden = isFlight || isCruise;
  document.querySelectorAll("#flightFields input, #flightFields select").forEach(el=>el.required=false);
  document.querySelectorAll("#cruiseFields input, #cruiseFields select").forEach(el=>el.required=false);
  if(isFlight){
    ["flightFrom","flightTo","flightDepartureDate","flightAdults"].forEach(id=>{const el=document.getElementById(id); if(el) el.required=true;});
  }
  if(isCruise){
    const adults=document.querySelector('[name="cruise_adults"]'); if(adults) adults.required=true;
  }
  if(returnDateField && flightReturnDate){
    const oneWay = flightTripType && flightTripType.value === "One way";
    returnDateField.style.display = oneWay ? "none" : "";
    flightReturnDate.required = !oneWay && isFlight;
  }
}


