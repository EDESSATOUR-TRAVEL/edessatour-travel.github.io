quoteForm.addEventListener("submit", async e=>{
  e.preventDefault();
  if(!quoteForm.checkValidity()){
    quoteForm.reportValidity();
    return;
  }

  const f = new FormData(quoteForm);
  if(f.get("_honey")){ return; }
  const selectedService = f.get("request_type") || "Website Inquiry";
  f.set("_subject", `EDESSATOUR Website — ${selectedService}`);
  f.set("_template", "table");

  const button = quoteForm.querySelector('button[type="submit"]');
  const originalText = button.textContent;
  button.disabled = true;
  button.textContent = lang === "ar" ? "جارٍ الإرسال..." : "Sending...";
  formStatus.textContent = "";
  formStatus.className = "form-status";

  try {
    const response = await fetch("https://formsubmit.co/ajax/EDESSATOUR@GMAIL.COM", {
      method: "POST",
      headers: { "Accept": "application/json" },
      body: f
    });

    const raw = await response.text();
    let result = {};
    try { result = raw ? JSON.parse(raw) : {}; } catch (_) { result = {}; }
    if(!response.ok || result.success === false){
      throw new Error("Submission failed");
    }

    formStatus.textContent = lang === "ar"
      ? "تم إرسال استفسارك بنجاح. سنتواصل معك قريباً."
      : "Your inquiry has been sent successfully. We will contact you soon.";
    formStatus.classList.add("success");
    quoteForm.reset();
    if(requestType) requestType.value = "Group Tour / Travel Program";
    if(tourSelect) tourSelect.value = "";
    updateProgramOptions();
    updateServiceFields();
  } catch(err) {
    formStatus.textContent = lang === "ar"
      ? "تعذر إرسال الاستفسار الآن. يرجى التواصل معنا عبر البريد أو WhatsApp."
      : "We could not send the inquiry right now. Please contact us by email or WhatsApp.";
    formStatus.classList.add("error");
  } finally {
    button.disabled = false;
    button.textContent = originalText;
  }
});
